/**
 * Keeps the copy of src/mbox.js inside public/index.html current.
 *
 *   node scripts/sync-mbox.mjs           rewrite the copy
 *   node scripts/sync-mbox.mjs --check   exit 1 when it is stale
 *
 * The page and the Worker split mbox files with the same code, so the code is
 * written once, in src/mbox.js, and pasted between two markers in the page
 * inside a function (its names then cannot collide with the page's own). The
 * pasted text is the file itself with "export " taken off, which is what the
 * test compares against.
 */
import { readFileSync, writeFileSync } from "node:fs";

const page = new URL("../public/index.html", import.meta.url);
const html = readFileSync(page, "utf8");
const eol = html.includes("\r\n") ? "\r\n" : "\n";
const src = readFileSync(new URL("../src/mbox.js", import.meta.url), "utf8").replace(/\r\n/g, "\n");
const names = [...src.matchAll(/^export (?:class|function|const) (\w+)/gm)].map((m) => m[1]);
const body = src.replace(/^export /gm, "");
const block = `/* mbox:begin — generated by scripts/sync-mbox.mjs from src/mbox.js; do not edit here */\nconst mbox = (() => {\n${body}\nreturn { ${names.join(", ")} };\n})();\n/* mbox:end */`.replace(/\n/g, eol);

const re = /\/\* mbox:begin[^\n]*\n[\s\S]*?\/\* mbox:end \*\//;
if (!re.test(html)) {
  console.error("public/index.html has no mbox:begin / mbox:end markers");
  process.exit(1);
}
const next = html.replace(re, () => block);
if (process.argv.includes("--check")) {
  if (next !== html) {
    console.error("the mbox copy in public/index.html is stale: run node scripts/sync-mbox.mjs");
    process.exit(1);
  }
} else if (next !== html) {
  writeFileSync(page, next);
  console.log("public/index.html: mbox copy updated");
}
